create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.catalog_items (
  id bigint generated by default as identity primary key,
  category text not null check (category in (
    'home-showcase',
    'phone-sales',
    'phone-repairs',
    'laptop-sales',
    'laptop-repairs',
    'gadgets',
    'phone-parts'
  )),
  title text not null,
  description text not null default '',
  price text not null default '',
  model text not null default '',
  part_category text not null default 'Accessories',
  target text not null default 'phones' check (target in ('phones', 'repairs', 'laptops', 'gadgets')),
  stock text not null default '',
  image text not null default '',
  visible boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.is_catalog_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

alter table public.admin_users enable row level security;
alter table public.catalog_items enable row level security;

drop policy if exists "Admins can read their own admin membership" on public.admin_users;
create policy "Admins can read their own admin membership"
  on public.admin_users for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Anyone can read visible catalog items" on public.catalog_items;
create policy "Anyone can read visible catalog items"
  on public.catalog_items for select to anon, authenticated
  using (visible or (select public.is_catalog_admin()));

drop policy if exists "Catalog admins can insert catalog items" on public.catalog_items;
create policy "Catalog admins can insert catalog items"
  on public.catalog_items for insert to authenticated
  with check ((select public.is_catalog_admin()));

drop policy if exists "Catalog admins can update catalog items" on public.catalog_items;
create policy "Catalog admins can update catalog items"
  on public.catalog_items for update to authenticated
  using ((select public.is_catalog_admin()))
  with check ((select public.is_catalog_admin()));

drop policy if exists "Catalog admins can delete catalog items" on public.catalog_items;
create policy "Catalog admins can delete catalog items"
  on public.catalog_items for delete to authenticated
  using ((select public.is_catalog_admin()));

grant select on public.admin_users to authenticated;
grant select on public.catalog_items to anon, authenticated;
grant insert, update, delete on public.catalog_items to authenticated;
grant usage, select on sequence public.catalog_items_id_seq to authenticated;
grant execute on function public.is_catalog_admin() to anon, authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'catalog-images',
  'catalog-images',
  true,
  8388608,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Catalog images are public" on storage.objects;
create policy "Catalog images are public"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'catalog-images');

drop policy if exists "Catalog admins can upload images" on storage.objects;
create policy "Catalog admins can upload images"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'catalog-images' and (select public.is_catalog_admin()));

drop policy if exists "Catalog admins can update images" on storage.objects;
create policy "Catalog admins can update images"
  on storage.objects for update to authenticated
  using (bucket_id = 'catalog-images' and (select public.is_catalog_admin()))
  with check (bucket_id = 'catalog-images' and (select public.is_catalog_admin()));

drop policy if exists "Catalog admins can delete images" on storage.objects;
create policy "Catalog admins can delete images"
  on storage.objects for delete to authenticated
  using (bucket_id = 'catalog-images' and (select public.is_catalog_admin()));
